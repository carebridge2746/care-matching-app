import type { QuizQuestion, TrainingCourse, TrainingCourseDetail, TrainingLesson } from '@/types';

/**
 * 교육 과정의 내용.
 *
 * Supabase 모드에서는 이 내용이 데이터베이스에 있다(supabase/schema.sql 의 Phase 9 절에서
 * 같은 식별자로 심는다). 여기 있는 것은 Mock 모드가 읽는 사본이며,
 * `auth.mock.ts` 의 시연 계정이나 `caregiver.demo.ts` 의 시연 프로필과 같은 자리다.
 *
 * 두 곳을 함께 고쳐야 한다. 그럼에도 내용을 앱 번들이 아니라 데이터베이스에 두는 이유는,
 * 교육 자료가 앱 배포와 상관없이 늘어나고 고쳐지는 것이기 때문이다 —
 * 문장 하나 다듬는 데 심사를 기다려야 한다면 아무도 고치지 않는다.
 *
 * 식별자는 고정값이다. 다시 심어도 같은 값이어야 응시·수료 기록이 과정을 잃지 않는다.
 */

/** 채점에 필요한 값까지 담은 문항. 화면으로 나갈 때는 QuizQuestion 으로 좁혀서 내보낸다. */
export type SeedQuizQuestion = QuizQuestion & {
  /** 정답 보기 번호(1부터) */
  answerIndex: number;
  explanation: string;
};

export type SeedCourse = TrainingCourseDetail & {
  questions: SeedQuizQuestion[];
};

type SeedCourseInput = Omit<TrainingCourse, 'questionCount'> & {
  lessons: TrainingLesson[];
  questions: SeedQuizQuestion[];
};

/** 문항 수는 세어서 붙인다. 손으로 적어 두면 문항을 늘릴 때 한쪽만 고치게 된다. */
function toCourse(input: SeedCourseInput): SeedCourse {
  const { lessons, questions, ...course } = input;
  return { ...course, questionCount: questions.length, lessons, questions };
}

